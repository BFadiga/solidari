-- =============================================================================
-- Solidari — schema inicial (Oracle Database 19c ou superior)
--
-- O banco e a fonte de verdade do schema: o Hibernate roda em
-- ddl-auto=validate e nao altera nada por conta propria.
--
-- Decisoes de portabilidade:
--   * Chaves primarias com IDENTITY (Oracle 12c+), equivalente ao BIGSERIAL.
--   * Valores monetarios em NUMBER(10,2): ponto flutuante acumula erro de
--     arredondamento e nao e tipo aceitavel para saldo/doacao.
--   * Flags em NUMBER(1) com CHECK (0,1). O tipo BOOLEAN em coluna so existe a
--     partir do Oracle 23ai; NUMBER(1) roda tambem no Oracle 19c da FIAP.
--   * Datas em TIMESTAMP com DEFAULT LOCALTIMESTAMP (fuso da sessao, o mesmo
--     que o Java usa no LocalDateTime).
-- =============================================================================

-- -----------------------------------------------------------------------------
-- usuarios — cadastro e carteira de credito
-- -----------------------------------------------------------------------------
CREATE TABLE usuarios (
    id          NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    nome        VARCHAR2(120)   NOT NULL,
    email       VARCHAR2(180)   NOT NULL,
    -- Hash BCrypt (60 caracteres). A senha em claro nunca e persistida.
    senha       VARCHAR2(100)   NOT NULL,
    saldo       NUMBER(10, 2)   DEFAULT 0 NOT NULL,
    papel       VARCHAR2(20)    DEFAULT 'USUARIO' NOT NULL,
    criado_em   TIMESTAMP       DEFAULT LOCALTIMESTAMP NOT NULL,

    CONSTRAINT pk_usuarios           PRIMARY KEY (id),
    CONSTRAINT uk_usuarios_email     UNIQUE (email),
    CONSTRAINT ck_usuarios_saldo     CHECK (saldo >= 0),
    CONSTRAINT ck_usuarios_papel     CHECK (papel IN ('USUARIO', 'ADMIN'))
);

COMMENT ON TABLE  usuarios       IS 'Usuarios do app Solidari, com saldo de cashback disponivel para doacao';
COMMENT ON COLUMN usuarios.senha IS 'Hash BCrypt da senha; nunca armazenar texto puro';
COMMENT ON COLUMN usuarios.saldo IS 'Credito de cashback acumulado e ainda nao doado, em reais';

-- -----------------------------------------------------------------------------
-- parceiros — estabelecimentos que geram cashback
-- -----------------------------------------------------------------------------
CREATE TABLE parceiros (
    id                   NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    nome                 VARCHAR2(120)   NOT NULL,
    descricao            VARCHAR2(255)   NOT NULL,
    categoria            VARCHAR2(60)    NOT NULL,
    -- Rotulo exibido no app (ex.: '15% CASHBACK'). E texto de interface:
    -- o calculo usa percentual_cashback, nunca esta coluna.
    badge                VARCHAR2(40)    NOT NULL,
    percentual_cashback  NUMBER(5, 2)    DEFAULT 0 NOT NULL,
    imagem_url           VARCHAR2(500),
    destaque             NUMBER(1)       DEFAULT 0 NOT NULL,
    latitude             FLOAT(53),
    longitude            FLOAT(53),
    ativo                NUMBER(1)       DEFAULT 1 NOT NULL,
    criado_em            TIMESTAMP       DEFAULT LOCALTIMESTAMP NOT NULL,

    CONSTRAINT pk_parceiros            PRIMARY KEY (id),
    CONSTRAINT ck_parceiros_percentual CHECK (percentual_cashback BETWEEN 0 AND 100),
    CONSTRAINT ck_parceiros_destaque   CHECK (destaque IN (0, 1)),
    CONSTRAINT ck_parceiros_ativo      CHECK (ativo IN (0, 1)),
    CONSTRAINT ck_parceiros_latitude   CHECK (latitude  IS NULL OR latitude  BETWEEN  -90 AND  90),
    CONSTRAINT ck_parceiros_longitude  CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

COMMENT ON TABLE  parceiros                     IS 'Estabelecimentos parceiros que devolvem parte do consumo como credito';
COMMENT ON COLUMN parceiros.percentual_cashback IS 'Percentual do consumo devolvido como credito (0 a 100)';
COMMENT ON COLUMN parceiros.ativo               IS '1 = ativo, 0 = inativo';

-- -----------------------------------------------------------------------------
-- transacoes — consumo do usuario no parceiro; origem do credito
-- -----------------------------------------------------------------------------
CREATE TABLE transacoes (
    id               NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    usuario_id       NUMBER(19)      NOT NULL,
    parceiro_id      NUMBER(19)      NOT NULL,
    valor            NUMBER(10, 2)   NOT NULL,
    cashback_gerado  NUMBER(10, 2),
    status           VARCHAR2(20)    DEFAULT 'PENDENTE' NOT NULL,
    erro             VARCHAR2(400),
    data             TIMESTAMP       DEFAULT LOCALTIMESTAMP NOT NULL,
    processada_em    TIMESTAMP,

    CONSTRAINT pk_transacoes          PRIMARY KEY (id),
    CONSTRAINT fk_transacoes_usuario  FOREIGN KEY (usuario_id)  REFERENCES usuarios  (id),
    CONSTRAINT fk_transacoes_parceiro FOREIGN KEY (parceiro_id) REFERENCES parceiros (id),
    CONSTRAINT ck_transacoes_valor    CHECK (valor > 0),
    CONSTRAINT ck_transacoes_status   CHECK (status IN ('PENDENTE', 'PROCESSADA', 'ERRO'))
);

COMMENT ON TABLE  transacoes                 IS 'Compras do usuario em parceiros; processadas em lote viram credito';
COMMENT ON COLUMN transacoes.cashback_gerado IS 'Credito apurado no processamento; nulo enquanto PENDENTE';
COMMENT ON COLUMN transacoes.status          IS 'PENDENTE ate o processamento; PROCESSADA ou ERRO depois';

-- -----------------------------------------------------------------------------
-- doacoes — conversao de credito em impacto social
-- -----------------------------------------------------------------------------
CREATE TABLE doacoes (
    id                 NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    usuario_id         NUMBER(19)      NOT NULL,
    parceiro_id        NUMBER(19),
    valor              NUMBER(10, 2)   NOT NULL,
    categoria_impacto  VARCHAR2(40)    NOT NULL,
    data               TIMESTAMP       DEFAULT LOCALTIMESTAMP NOT NULL,

    CONSTRAINT pk_doacoes           PRIMARY KEY (id),
    CONSTRAINT fk_doacoes_usuario   FOREIGN KEY (usuario_id)  REFERENCES usuarios  (id),
    CONSTRAINT fk_doacoes_parceiro  FOREIGN KEY (parceiro_id) REFERENCES parceiros (id),
    CONSTRAINT ck_doacoes_valor     CHECK (valor > 0),
    CONSTRAINT ck_doacoes_categoria CHECK (categoria_impacto IN ('RESTAURACAO_AMBIENTAL', 'BEM_ESTAR_COMUNITARIO'))
);

COMMENT ON TABLE  doacoes                   IS 'Doacoes feitas com o credito de cashback do usuario';
COMMENT ON COLUMN doacoes.categoria_impacto IS 'Define a conversao em impacto: arvores plantadas ou refeicoes servidas';

-- -----------------------------------------------------------------------------
-- alertas — saida das rotinas automatizadas do banco
-- -----------------------------------------------------------------------------
CREATE TABLE alertas (
    id           NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY,
    tipo         VARCHAR2(40)   NOT NULL,
    severidade   VARCHAR2(20)   DEFAULT 'INFO' NOT NULL,
    descricao    VARCHAR2(400)  NOT NULL,
    usuario_id   NUMBER(19),
    parceiro_id  NUMBER(19),
    resolvido    NUMBER(1)      DEFAULT 0 NOT NULL,
    criado_em    TIMESTAMP      DEFAULT LOCALTIMESTAMP NOT NULL,

    CONSTRAINT pk_alertas            PRIMARY KEY (id),
    CONSTRAINT fk_alertas_usuario    FOREIGN KEY (usuario_id)  REFERENCES usuarios  (id),
    CONSTRAINT fk_alertas_parceiro   FOREIGN KEY (parceiro_id) REFERENCES parceiros (id),
    CONSTRAINT ck_alertas_severidade CHECK (severidade IN ('INFO', 'ATENCAO', 'CRITICO')),
    CONSTRAINT ck_alertas_resolvido  CHECK (resolvido IN (0, 1))
);

COMMENT ON TABLE alertas IS 'Alertas gerados por pkg_monitoramento e por triggers, consumidos pelo dashboard';

-- -----------------------------------------------------------------------------
-- auditoria_saldo — trilha de toda alteracao de saldo (alimentada por trigger)
--
-- Fica fora do mapeamento JPA de proposito: e uma tabela so do banco, que nem
-- o Java nem o app conseguem "esquecer" de preencher.
-- -----------------------------------------------------------------------------
CREATE TABLE auditoria_saldo (
    id               NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    usuario_id       NUMBER(19)      NOT NULL,
    saldo_anterior   NUMBER(10, 2)   NOT NULL,
    saldo_novo       NUMBER(10, 2)   NOT NULL,
    diferenca        NUMBER(10, 2)   NOT NULL,
    operacao         VARCHAR2(20)    NOT NULL,
    usuario_banco    VARCHAR2(128)   NOT NULL,
    modulo           VARCHAR2(64),
    registrado_em    TIMESTAMP       DEFAULT LOCALTIMESTAMP NOT NULL,

    CONSTRAINT pk_auditoria_saldo         PRIMARY KEY (id),
    CONSTRAINT fk_auditoria_saldo_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_auditoria_saldo_operacao CHECK (operacao IN ('CREDITO', 'DEBITO'))
);

COMMENT ON TABLE  auditoria_saldo           IS 'Historico imutavel de alteracoes de saldo, gravado pela trigger trg_auditoria_saldo';
COMMENT ON COLUMN auditoria_saldo.operacao  IS 'CREDITO quando o saldo sobe (cashback), DEBITO quando desce (doacao)';
COMMENT ON COLUMN auditoria_saldo.modulo    IS 'Programa que fez a alteracao (SYS_CONTEXT MODULE), util para rastrear a origem';

-- -----------------------------------------------------------------------------
-- Indices de apoio as consultas mais frequentes
-- -----------------------------------------------------------------------------
CREATE INDEX idx_doacoes_usuario_data   ON doacoes    (usuario_id, data DESC);
CREATE INDEX idx_doacoes_categoria      ON doacoes    (categoria_impacto);
CREATE INDEX idx_doacoes_parceiro       ON doacoes    (parceiro_id);
CREATE INDEX idx_transacoes_status      ON transacoes (status);
CREATE INDEX idx_transacoes_usuario     ON transacoes (usuario_id);
CREATE INDEX idx_transacoes_parceiro    ON transacoes (parceiro_id, data);
CREATE INDEX idx_parceiros_categoria    ON parceiros  (categoria);
CREATE INDEX idx_alertas_resolvido      ON alertas    (resolvido, criado_em DESC);
CREATE INDEX idx_auditoria_usuario      ON auditoria_saldo (usuario_id, registrado_em DESC);
